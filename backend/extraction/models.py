from django.db import models

class StatusChoices(models.TextChoices):
    PENDING = 'PENDING', 'Oczekujący'
    PROCESSING = 'PROCESSING', 'Przetwarzany'
    COMPLETED = 'COMPLETED', 'Ukończony'
    APPROVED = 'APPROVED', 'Zatwierdzony'
    CORRECTED = 'CORRECTED', 'Poprawiony'
    REJECTED = 'REJECTED', 'Odrzucony'
    FAILED = 'FAILED', 'Błąd'

class ExtractionResult(models.Model):
    """
    Stores extraction results or medical reports (in JSON format)
    linked with the study, AI model version, and verification process.
    """
    study = models.ForeignKey(
        'patients.Study', 
        on_delete=models.CASCADE, 
        null=True,
        blank=True, 
        related_name='extractions'
    )
    model = models.ForeignKey(
        'mlops.ModelVersion', 
        on_delete=models.SET_NULL, 
        null=True, 
        blank=True,
        related_name='extraction_results'
    )
    status = models.CharField(
        max_length=20, 
        choices=StatusChoices.choices, 
        default=StatusChoices.PENDING
    )
    uncertainty = models.FloatField(blank=True, null=True)

    report_path = models.CharField(max_length=500, blank=True, null=True)
    # JSON reports generated by AI and verified by a doctor
    generated_report = models.JSONField(blank=True, null=True, help_text="Initial report automatically generated by the AI model")
    accepted_report = models.JSONField(blank=True, null=True, help_text="Final report approved or corrected by the doctor")

    # Written by the extraction worker (workers/extraction/tasks.py); no report text in any of them.
    error = models.TextField(
        blank=True, default="", help_text="Why the extraction failed (status FAILED)"
    )
    warnings = models.JSONField(
        default=list, blank=True, help_text="Fields that do not follow from the report text"
    )
    provenance = models.JSONField(
        blank=True,
        null=True,
        help_text="LLM model, prompt, schema and OCR that produced the result",
    )
    created_at = models.DateTimeField(auto_now_add=True)
    # Changes on every status change, so a stage stuck in PROCESSING can be detected.
    updated_at = models.DateTimeField(auto_now=True)

    # Human-in-the-loop verification metadata
    accepted_by = models.ForeignKey(
        'users.User', 
        on_delete=models.SET_NULL, 
        null=True, 
        blank=True, 
        related_name='accepted_extractions'
    )
    accepted_at = models.DateField(blank=True, null=True)

    class Meta:
        db_table = 'extraction_results'

    def __str__(self):
        return f"Extraction #{self.id} (Study: {self.study_id}) [Status: {self.status}]"