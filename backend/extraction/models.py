from django.db import models
from django.db.models import F


class StatusChoices(models.TextChoices):
    UPLOADED = "UPLOADED", "Wgrany"  # stored, processing not ordered yet
    PENDING = "PENDING", "Oczekujący"
    PROCESSING = "PROCESSING", "Przetwarzany"
    COMPLETED = "COMPLETED", "Ukończony"
    APPROVED = "APPROVED", "Zatwierdzony"
    CORRECTED = "CORRECTED", "Poprawiony"
    REJECTED = "REJECTED", "Odrzucony"
    FAILED = "FAILED", "Błąd"


class FailedStepChoices(models.TextChoices):
    OCR = "ocr", "OCR"
    LLM = "llm", "LLM"


class SourceChoices(models.TextChoices):
    SCAN = "scan", "Skan"  # image, read by OCR
    TEXT = "text", "Tekst"  # text file, no OCR
    MANUAL = "manual", "Ręczny"  # form filled in by the radiologist, no file

    @classmethod
    def of_file(cls, name: str) -> "SourceChoices":
        """Source of an uploaded report file by its name: .txt is text, anything else a scan."""
        return cls.TEXT if name.lower().endswith(".txt") else cls.SCAN


class ExtractionQuerySet(models.QuerySet):
    """A study can have several reports; the active one is the one assigned to it last.

    Not the highest id: a report uploaded earlier and assigned later (attach-existing-report)
    is older by id but is the one the user just chose.
    """

    def oldest_assigned_first(self):
        # rows from before assigned_at existed (NULL) count as the oldest
        return self.order_by(F("assigned_at").asc(nulls_first=True), "id")

    def active(self):
        """The active report of the filtered rows, or None."""
        return self.order_by(F("assigned_at").desc(nulls_last=True), "-id").first()


class ExtractionResult(models.Model):
    """
    A report through its whole life: uploaded, processed (OCR, then LLM), verified by a
    radiologist. One row per report; the table is ``reports``.
    """

    # A report outlives its study: deleting the study leaves it unassigned (docs/database.md).
    study = models.ForeignKey(
        "patients.Study",
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="extractions",
    )
    # the extraction version (module ext); empty for a manual form
    model = models.ForeignKey(
        "mlops.ModelVersion",
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="extraction_results",
    )
    # the OCR version (module ocr); empty for text and manual reports
    ocr_model = models.ForeignKey(
        "mlops.ModelVersion",
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="ocr_results",
    )
    # UPLOADED until someone orders the processing or the report is assigned to a study
    status = models.CharField(
        max_length=20, choices=StatusChoices.choices, default=StatusChoices.UPLOADED
    )
    uncertainty = models.FloatField(blank=True, null=True)

    report_path = models.CharField(max_length=500, blank=True, null=True)
    # Set by the backend when the row is created, never sent by the client.
    source = models.CharField(
        max_length=10,
        choices=SourceChoices.choices,
        default=SourceChoices.SCAN,
    )
    # JSON reports generated by AI and verified by a doctor
    generated_report = models.JSONField(
        blank=True, null=True, help_text="Initial report automatically generated by the AI model"
    )
    accepted_report = models.JSONField(
        blank=True, null=True, help_text="Final report approved or corrected by the doctor"
    )
    # Every field on the review screen by its path in accepted_report:
    # {"zmiany.0.obserwacje.1.brzeg": "confirmed" | "corrected" | "unverified"}
    field_checks = models.JSONField(
        blank=True,
        null=True,
        help_text="The doctor's check of each field on screen, by its path in the report",
    )

    # Written by the extraction worker (workers/extraction/tasks.py). Only ocr_text holds the
    # report text; error and warnings never do.
    failed_step = models.CharField(
        max_length=3, choices=FailedStepChoices.choices, blank=True, default=""
    )
    error = models.TextField(
        blank=True, default="", help_text="Why the extraction failed (status FAILED)"
    )
    # the OCR step
    ocr_text = models.TextField(
        blank=True, default="", help_text="The normalised report text that was sent to the LLM"
    )
    ocr_confidence = models.FloatField(blank=True, null=True)
    ocr_seconds = models.FloatField(blank=True, null=True)
    ocr_engine_version = models.CharField(max_length=50, blank=True, default="")
    page_rotations = models.JSONField(default=list, blank=True)
    # the LLM step
    warnings = models.JSONField(
        default=list, blank=True, help_text="Fields that do not follow from the report text"
    )
    llm_seconds = models.FloatField(blank=True, null=True)
    attempts = models.PositiveSmallIntegerField(default=0)
    schema_version = models.CharField(max_length=10, blank=True, default="")
    created_at = models.DateTimeField(auto_now_add=True)
    # When the report was assigned to its study (at upload or later); picks the active report.
    assigned_at = models.DateTimeField(blank=True, null=True)
    # Changes on every status change, so a stage stuck in PROCESSING can be detected.
    updated_at = models.DateTimeField(auto_now=True)

    # Human-in-the-loop verification metadata
    accepted_by = models.ForeignKey(
        "users.User",
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="accepted_extractions",
    )
    accepted_at = models.DateField(blank=True, null=True)
    # Who ordered the processing: uploaded the report or asked for it to be processed again.
    requested_by = models.ForeignKey(
        "users.User",
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="requested_extractions",
    )

    objects = ExtractionQuerySet.as_manager()

    class Meta:
        db_table = "reports"

    def __str__(self):
        return f"Extraction #{self.id} (Study: {self.study_id}) [Status: {self.status}]"
