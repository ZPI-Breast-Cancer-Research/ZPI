from django.db import models
from django.db.models import F

class StatusChoices(models.TextChoices):
    PENDING = 'PENDING', 'Oczekujący'
    PROCESSING = 'PROCESSING', 'Przetwarzany'
    COMPLETED = 'COMPLETED', 'Ukończony'
    APPROVED = 'APPROVED', 'Zatwierdzony'
    CORRECTED = 'CORRECTED', 'Poprawiony'
    REJECTED = 'REJECTED', 'Odrzucony'
    FAILED = 'FAILED', 'Błąd'

class ExtractionQuerySet(models.QuerySet):
    """A study can have several reports; the active one is the one assigned to it last.

    Not the highest id: a report uploaded earlier and assigned later (attach-existing-report)
    is older by id but is the one the user just chose.
    """

    def oldest_assigned_first(self):
        # rows from before assigned_at existed (NULL) count as the oldest
        return self.order_by(F("assigned_at").asc(nulls_first=True), "id")

    def active(self):
        """The active report of the filtered rows, or None."""
        return self.order_by(F("assigned_at").desc(nulls_last=True), "-id").first()


class ExtractionResult(models.Model):
    """
    Stores extraction results or medical reports (in JSON format)
    linked with the study, AI model version, and verification process.
    """
    study = models.ForeignKey(
        'patients.Study', 
        on_delete=models.CASCADE, 
        null=True,
        blank=True, 
        related_name='extractions'
    )
    model = models.ForeignKey(
        'mlops.ModelVersion', 
        on_delete=models.SET_NULL, 
        null=True, 
        blank=True,
        related_name='extraction_results'
    )
    status = models.CharField(
        max_length=20, 
        choices=StatusChoices.choices, 
        default=StatusChoices.PENDING
    )
    uncertainty = models.FloatField(blank=True, null=True)

    report_path = models.CharField(max_length=500, blank=True, null=True)
    # JSON reports generated by AI and verified by a doctor
    generated_report = models.JSONField(blank=True, null=True, help_text="Initial report automatically generated by the AI model")
    accepted_report = models.JSONField(blank=True, null=True, help_text="Final report approved or corrected by the doctor")
    # The doctor's answer per lesion index and field: {"0": {"birads": {"value": "4C", "state": "confirmed"}}}
    lesion_answers = models.JSONField(
        blank=True, null=True, help_text="Confirmed or corrected fields per lesion, from the review form"
    )
    # Every field on the review screen by its path in accepted_report:
    # {"zmiany.0.obserwacje.1.brzeg": "confirmed" | "corrected" | "unverified"}
    field_checks = models.JSONField(
        blank=True,
        null=True,
        help_text="The doctor's check of each field on screen, by its path in the report",
    )

    # Written by the extraction worker (workers/extraction/tasks.py). generated_report, error,
    # warnings and provenance hold no report text; result does (the OCR text and the quotes).
    result = models.JSONField(
        blank=True,
        null=True,
        help_text=(
            "Full ExtractionResult of the worker (workers/extraction/schema.py): data, OCR text, "
            "warnings, provenance; what the frontend shows as the report"
        ),
    )
    error = models.TextField(
        blank=True, default="", help_text="Why the extraction failed (status FAILED)"
    )
    warnings = models.JSONField(
        default=list, blank=True, help_text="Fields that do not follow from the report text"
    )
    provenance = models.JSONField(
        blank=True,
        null=True,
        help_text="LLM model, prompt, schema and OCR that produced the result",
    )
    created_at = models.DateTimeField(auto_now_add=True)
    # When the report was assigned to its study (at upload or later); picks the active report.
    assigned_at = models.DateTimeField(blank=True, null=True)
    # Changes on every status change, so a stage stuck in PROCESSING can be detected.
    updated_at = models.DateTimeField(auto_now=True)

    # Human-in-the-loop verification metadata
    accepted_by = models.ForeignKey(
        'users.User', 
        on_delete=models.SET_NULL, 
        null=True, 
        blank=True, 
        related_name='accepted_extractions'
    )
    accepted_at = models.DateField(blank=True, null=True)

    objects = ExtractionQuerySet.as_manager()

    class Meta:
        db_table = 'extraction_results'

    def __str__(self):
        return f"Extraction #{self.id} (Study: {self.study_id}) [Status: {self.status}]"